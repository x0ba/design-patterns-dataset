import {chromium} from 'playwright-core';
const [,, base, out] = process.argv;
const exe = process.env.HOME + '/Library/Caches/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-mac-arm64/chrome-headless-shell';
const browser = await chromium.launch({executablePath: exe});
const page = await browser.newPage({viewport: {width: 1440, height: 900}});
page.on('console', m => { if (m.type() === 'error') console.log('console error:', m.text()); });
page.on('pageerror', e => console.log('pageerror', e.message));
await page.goto(base + '/seed.html');
await page.waitForURL(base + '/');
await page.waitForTimeout(3000);
await page.screenshot({path: out + '-home.png'});
const first = page.locator('text=RECENT CHATS').locator('xpath=..').locator('button').first();
await first.click();
await page.waitForTimeout(1500);
await page.screenshot({path: out + '-chat.png'});
const ta = page.locator('textarea').first();
await ta.fill('hello there');
await ta.press('Enter');
await page.waitForTimeout(4000);
await page.screenshot({path: out + '-reply.png'});
await browser.close();
