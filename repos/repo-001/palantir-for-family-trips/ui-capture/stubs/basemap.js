function ellipse(lat, lng, rLat, rLng, steps = 18) {
  const ring = []
  for (let i = 0; i < steps; i += 1) {
    const a = (i / steps) * Math.PI * 2
    ring.push([lat + Math.sin(a) * rLat, lng + Math.cos(a) * rLng])
  }
  return ring
}
