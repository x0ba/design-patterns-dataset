import { chromium } from "playwright-core";
import { spawn } from "node:child_process";
const srv = spawn(process.execPath, ["serve.mjs", "../out", "5478"], { stdio: "inherit" });
await new Promise((r) => setTimeout(r, 800));
const exe = process.env.HOME + "/Library/Caches/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-mac-arm64/chrome-headless-shell";
const browser = await chromium.launch({ executablePath: exe });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const external = [];
page.on("console", (m) => { if (m.type() === "error" || m.text().includes("ui-capture")) console.log("console:", m.type(), m.text().slice(0, 200)); });
page.on("pageerror", (e) => console.log("pageerror:", e.message));
page.on("request", (r) => { if (!r.url().startsWith("http://localhost")) external.push(r.url()); });
await page.goto("http://localhost:5478/", { waitUntil: "networkidle" });
await page.waitForTimeout(1500);
await page.screenshot({ path: "01-live.png" });
await page.click("#connection-button");
await page.waitForTimeout(2000);
await page.screenshot({ path: "02-connected.png" });
await page.getByText("Paste", { exact: false }).first().click().catch((e) => console.log("nav", e.message));
await page.waitForTimeout(800);
await page.screenshot({ path: "03-paste.png" });
await page.getByText("Duckyscript").first().click();
await page.waitForTimeout(1000);
await page.screenshot({ path: "04-ducky.png" });
console.log("external requests:", [...new Set(external)].slice(0, 10));
await browser.close(); srv.kill();
